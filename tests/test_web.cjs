const {chromium}=require('playwright');
const fs=require('fs'),path=require('path');
const repo=path.resolve(__dirname,'..'),root=repo;
(async()=>{
const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});const page=await browser.newPage({viewport:{width:1440,height:1100}});const errors=[];page.on('pageerror',e=>errors.push(e.message));
const html=fs.readFileSync(path.join(repo,'firmware/esp32/web/index.html'),'utf8');
const frames=JSON.parse(fs.readFileSync(path.join(repo,'build/preview.json'),'utf8'));
await page.route('http://arcade.test/**',r=>r.fulfill({contentType:'text/html',body:html}));
let peer,messages=[];await page.routeWebSocket('ws://arcade.test:81/',ws=>{peer=ws;ws.onMessage(m=>{messages.push(m);if(m==='claim')ws.send(JSON.stringify({role:'controller'}));});});
await page.goto('http://arcade.test/');await page.waitForFunction(()=>document.querySelector('#launch').disabled===false);
peer.send(JSON.stringify({...frames[0],state:0}));await page.getByRole('button',{name:'TAKE FLIGHT'}).click();await page.waitForTimeout(160);
if(!messages.some(m=>/^i,.*?,.*?,0,1,0$/.test(m)))throw Error('launch did not send start command');
const frame=frames.reduce((a,b)=>a.rocks.length+a.particles.length*.05>b.rocks.length+b.particles.length*.05?a:b);
peer.send(JSON.stringify(frame));await page.waitForTimeout(100);
await page.keyboard.down('ArrowRight');await page.keyboard.down('Space');await page.waitForTimeout(80);await page.keyboard.up('ArrowRight');await page.keyboard.up('Space');
if(!messages.some(m=>m.startsWith('i,1.00,0.00,1,')))throw Error('keyboard controls failed');
await page.getByRole('button',{name:'PAUSE / P'}).click();await page.waitForTimeout(80);
if(!messages.some(m=>m.endsWith(',0,1')))throw Error('pause command failed');
await page.evaluate(()=>{document.querySelector('#connectionText').textContent='NATIVE SIMULATION PREVIEW';document.querySelector('#message').textContent='Real C++ engine snapshots · mocked network transport';});
await page.screenshot({path:path.join(repo,'build/orbital-desktop.png')});
await page.setViewportSize({width:390,height:844});await page.screenshot({path:path.join(repo,'build/orbital-mobile.png')});
if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('mobile horizontal overflow');
peer.send(JSON.stringify({...frame,state:2}));await page.getByRole('button',{name:'RESUME FLIGHT'}).waitFor();
peer.send(JSON.stringify({...frame,state:3}));await page.getByRole('button',{name:'FLY AGAIN'}).waitFor();
peer.close();await page.waitForFunction(()=>document.querySelector('#connectionText').textContent==='RECONNECTING');
if(errors.length)throw Error(errors.join('\n'));
console.log('PASS: launch, keyboard movement/fire, pause, state overlays, disconnect, desktop/mobile layout; zero JS errors');
await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
